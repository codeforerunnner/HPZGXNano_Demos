  const DICT_LOW = {};
  for (const [k, v] of Object.entries(DICT)) DICT_LOW[k.toLowerCase()] = v;

  const orig = new WeakMap();
  let lang = localStorage.getItem("zgx_demo_lang") || "es";
  let applying = false;

  function translateStr(s) {
    if (!s) return s;
    const trimmed = s.trim();
    if (!trimmed) return s;
    if (DICT[trimmed]) return s.replace(trimmed, DICT[trimmed]);
    const low = trimmed.toLowerCase();
    if (DICT_LOW[low]) return s.replace(trimmed, DICT_LOW[low]);
    return s;
  }

  const SKIP_TAGS = new Set(["SCRIPT", "STYLE", "NOSCRIPT", "SVG", "TEXTAREA", "CODE", "PRE"]);

  function applySubtree(root) {
    if (!root || (root.nodeType !== 1 && root.nodeType !== 3)) return;
    if (root.nodeType === 3) {
      const p = root.parentElement;
      if (p && (SKIP_TAGS.has(p.tagName) || p.closest("#zgx-i18n-bar, svg, pre, code, textarea, .md-output, .fury-msg-body, .mc-document-text"))) return;
      if (!orig.has(root)) orig.set(root, root.nodeValue);
      const enVal = orig.get(root);
      if (p && p.tagName === "OPTION" && !p.hasAttribute("value")) {
        p.setAttribute("value", enVal.trim());
      }
      const nv = lang === "es" ? translateStr(enVal) : enVal;
      if (root.nodeValue !== nv) root.nodeValue = nv;
      return;
    }
    if (SKIP_TAGS.has(root.tagName) || root.id === "zgx-i18n-bar") return;
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        const p = node.parentElement;
        if (!p || SKIP_TAGS.has(p.tagName) || p.closest("#zgx-i18n-bar, svg, pre, code, textarea, .md-output, .fury-msg-body, .mc-document-text")) {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    let n;
    while ((n = w.nextNode())) {
      if (!orig.has(n)) orig.set(n, n.nodeValue);
      const enVal = orig.get(n);
      const optParent = n.parentElement;
      if (optParent && optParent.tagName === "OPTION" && !optParent.hasAttribute("value")) {
        optParent.setAttribute("value", enVal.trim());
      }
      const nv = lang === "es" ? translateStr(enVal) : enVal;
      if (n.nodeValue !== nv) n.nodeValue = nv;
    }
    const phNodes = root.querySelectorAll ? root.querySelectorAll("input[placeholder],textarea[placeholder]") : [];
    for (const el of phNodes) {
      if (!el.dataset.zgxEnPh) el.dataset.zgxEnPh = el.placeholder;
      const enPh = el.dataset.zgxEnPh;
      const nv = lang === "es" ? (DICT[enPh] || DICT_LOW[enPh.toLowerCase()] || enPh) : enPh;
      if (el.placeholder !== nv) el.placeholder = nv;
    }
    const ariaNodes = root.querySelectorAll ? root.querySelectorAll("[aria-label]") : [];
    for (const el of ariaNodes) {
      if (el.closest("#zgx-i18n-bar")) continue;
      if (!el.dataset.zgxEnAria) el.dataset.zgxEnAria = el.getAttribute("aria-label") || "";
      const enAria = el.dataset.zgxEnAria;
      const nv = lang === "es" ? (DICT[enAria] || DICT_LOW[enAria.toLowerCase()] || enAria) : enAria;
      if (el.getAttribute("aria-label") !== nv) el.setAttribute("aria-label", nv);
    }
  }

  function applyDom() {
    if (applying) return;
    applying = true;
    try {
      applySubtree(document.body);
    } finally {
      applying = false;
    }
  }

  function mountBar() {
    if (document.getElementById("zgx-i18n-bar")) return;
    const bar = document.createElement("span");
    bar.id = "zgx-i18n-bar";
    bar.innerHTML =
      '<button type="button" id="zgx-btn-es">CASTELLANO</button>' +
      '<button type="button" id="zgx-btn-en">ENGLISH</button>';
    const topActions = document.querySelector(".top-actions, .hp-shell nav");
    if (topActions) {
      topActions.insertBefore(bar, topActions.firstChild);
    } else {
      bar.classList.add("zgx-floating");
      document.body.appendChild(bar);
    }
    document.getElementById("zgx-btn-es").addEventListener("click", () => window.__zgxSetLang("es"));
    document.getElementById("zgx-btn-en").addEventListener("click", () => window.__zgxSetLang("en"));
  }

  window.__zgxSetLang = function (l) {
    lang = l === "en" ? "en" : "es";
    localStorage.setItem("zgx_demo_lang", lang);
    const bEs = document.getElementById("zgx-btn-es");
    const bEn = document.getElementById("zgx-btn-en");
    if (bEs && bEn) {
      bEs.classList.toggle("active", lang === "es");
      bEn.classList.toggle("active", lang === "en");
    }
    applyDom();
  };

  function init() {
    mountBar();
    let pending = new Set();
    let rafId = 0;
    const obs = new MutationObserver((mutations) => {
      if (applying || lang !== "es") return;
      for (const m of mutations) {
        if (m.addedNodes && m.addedNodes.length) {
          for (const nd of m.addedNodes) pending.add(nd);
        }
      }
      if (!pending.size || rafId) return;
      rafId = requestAnimationFrame(() => {
        rafId = 0;
        const batch = Array.from(pending);
        pending.clear();
        applying = true;
        try {
          for (const nd of batch) {
            if (nd.isConnected) applySubtree(nd);
          }
        } finally {
          applying = false;
        }
      });
    });
    obs.observe(document.body, { childList: true, subtree: true });
    window.__zgxSetLang(lang);
  }

  if (document.readyState === "loading") {
    window.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
